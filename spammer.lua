-- ===================== 自定义刷屏：状态 =====================
local zd_next_send = 0
local zd_seq_index = 1      -- 非随机顺序的游标
local zd_remaining = {}     -- 随机顺序的剩余池（一轮不重复）
local zd_last_sig = nil     -- 池内容签名，变化时自动重置

-- 解析三个输入框，合并成一个消息列表（英文逗号分隔，自动去首尾空白）
local function zd_parse_pools()
    local list = {}
    for _, box in ipairs({ zd_pool_a, zd_pool_b, zd_pool_c }) do
        local ok, text = pcall(function() return box:get() end)
        if ok and type(text) == 'string' then
            for s in text:gmatch('[^,]+') do
                s = s:gsub('^%s+', ''):gsub('%s+$', '')
                if s ~= '' then list[#list + 1] = s end
            end
        end
    end
    return list
end

local function zd_send_next()
    if not zd_enable:get() then return end
    if not engine.in_game() then return end

    local list = zd_parse_pools()
    if #list == 0 then return end

    -- 池内容变动时重置发送进度
    local sig = table.concat(list, '\1')
    if sig ~= zd_last_sig then
        zd_last_sig = sig
        zd_remaining = {}
        zd_seq_index = 1
    end

    local msg
    if zd_random:get() then
        -- 与 zdmar 一致：一轮内不重复，发完一轮才重新洗牌
        if #zd_remaining == 0 then
            zd_remaining = {}
            for i = 1, #list do zd_remaining[i] = list[i] end
            for i = #zd_remaining, 2, -1 do
                local j = math.random(i)
                zd_remaining[i], zd_remaining[j] = zd_remaining[j], zd_remaining[i]
            end
        end
        msg = table.remove(zd_remaining)
    else
        msg = list[zd_seq_index]
        zd_seq_index = zd_seq_index + 1
        if zd_seq_index > #list then zd_seq_index = 1 end
    end

    local cmd = (comboIndex(zd_mode) == 1) and 'say_team' or 'say'
    pcall(function() engine.exec(cmd .. ' "' .. msg .. '"') end)

    if zd_log:get() then
        pcall(function() log.console('[自定义] ' .. cmd .. ': ' .. msg) end)
    end

    local iv = clamp(zd_interval:get() or 1.0, 0.1, 10.0)
    zd_next_send = (globals.curtime and globals.curtime() or os.clock()) + iv
end


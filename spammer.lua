-- ===================== 公共工具 =====================
local function member(obj, key, ...)
    if type(obj) ~= 'table' and type(obj) ~= 'userdata' then return nil end
    local ok0, v = pcall(function() return obj[key] end)
    if not ok0 then return nil end
    if type(v) == 'function' then
        local ok, r = pcall(v, obj, ...)
        if ok then return r end
        ok, r = pcall(v, ...)
        if ok then return r end
        return nil
    end
    return v
end

local function gval(name)
    local v = globals[name]
    if type(v) == 'function' then
        local ok, r = pcall(v)
        if ok then return r end
        return nil
    end
    return v
end

local function safe_num(x)
    local n = tonumber(x)
    return n or 0
end

local function clamp(x, mn, mx)
    if x < mn then return mn end
    if x > mx then return mx end
    return x
end

local function comboIndex(elem)
    local ok, v = pcall(function() return elem:get() end)
    if not ok then return 0 end
    if type(v) == 'number' then return v end
    if type(v) == 'string' then
        if v:find('队伍') or v:find('team') then return 1 end
        if v:find('公屏') or v:find('all') then return 0 end
    end
    return 0
end

-- ===================== 实体辅助 =====================
local function local_pawn()
    local ctrl = member(entity, 'local_controller')
    if ctrl then
        local p = member(ctrl, 'pawn')
        if p then return p end
    end
    return member(entity, 'local_pawn')
end

local function read_team(ent)
    if not ent then return nil end
    local t = member(ent, 'team')
    if t == nil then t = member(ent, 'teamnum') end
    if t == nil then t = member(ent, 'm_iTeamNum') end
    if type(t) == 'string' then t = tonumber(t) end
    return t
end

